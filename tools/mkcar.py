#!/usr/bin/env python3
"""The player's car as the game draws it, from renders of its 3D model.

tools/car3d.py (run in Blender) renders the car seen from behind, straight
and turning left, into assets/car/car_0.png and car_left.png: a frame of
CELLS mode 0 pixels, each CELL_PX render pixels, its middle column the
screen's. This turns them into tools/carart.py, the art scene.py draws and
mkbush.py makes code of:

- each cell is the pen most of its pixels are (none if most are clear);
- a lone cell is dropped;
- a row's ends are outlined in black, as a sprite's;
- each row's run is widened to whole pairs (4 pixels) and its gaps filled
  with the asphalt's grey (the engine draws a line's run with PUSHes) -
  pairs from the box's left edge, the box the same either side of the
  middle, so turning right - the left view mirrored - fits it too, and as
  wide as the widest view needs: of the two ways the pairs can fall
  (the edge 0 or 2 pixels past a multiple of 4), the one with the fewer
  pixels to draw.
"""

import os
import sys
from collections import Counter

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cpcgfx import PEN, pen_rgb  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "assets", "car")
CELLS = (64, 40)
CELL_PX = (16, 8)
MID = CELLS[0] // 2

# letter -> pen, as scene.py CAR_PEN
LETTERS = dict(R="RED", O="ORANGE", Y="YELLOW", K="BLACK", G="GREY",
               W="WHITE", N="NAVY", S="SKY", D="CAR_DARK")
BODY = "ROD"                            # what an outline replaces


def cells(path):
    """The render as rows of letters ('.' clear)."""
    im = Image.open(path).convert("RGBA")
    assert im.size == (CELLS[0] * CELL_PX[0], CELLS[1] * CELL_PX[1]), im.size
    px = im.load()
    rgb = {c: pen_rgb(PEN[p]) for c, p in LETTERS.items()}   # (grey: the hubs)
    near = {}
    rows = []
    for cy in range(CELLS[1]):
        row = ""
        for cx in range(CELLS[0]):
            n = Counter()
            for y in range(cy * CELL_PX[1], (cy + 1) * CELL_PX[1]):
                for x in range(cx * CELL_PX[0], (cx + 1) * CELL_PX[0]):
                    r, g, b, a = px[x, y]
                    if a < 128:
                        n["."] += 1
                        continue
                    if (r, g, b) not in near:
                        near[r, g, b] = min(rgb, key=lambda c: sum(
                            (u - v) ** 2 for u, v in zip((r, g, b), rgb[c])))
                    n[near[r, g, b]] += 1
            row += n.most_common(1)[0][0]
        rows.append(row)
    return rows


def lone(rows):
    """Cells with nothing next to them across or up and down: dropped."""
    def at(x, y):
        return rows[y][x] if 0 <= y < len(rows) and 0 <= x < len(rows[y]) else "."
    return ["".join("." if c != "." and all(at(x + dx, y + dy) == "." for dx, dy in
                                            ((-1, 0), (1, 0), (0, -1), (0, 1))) else c
                    for x, c in enumerate(r)) for y, r in enumerate(rows)]


def outline(rows):
    """A row's first and last cells black, if they are the body's."""
    out = []
    for r in rows:
        r = list(r)
        xs = [i for i, c in enumerate(r) if c != "."]
        for i in xs[:1] + xs[-1:]:
            if r[i] in BODY:
                r[i] = "K"
        out.append("".join(r))
    return out


def pairs(r, p):
    """The row's run widened to whole pairs from p (0 or 2), its gaps grey."""
    xs = [i for i, c in enumerate(r) if c != "."]
    if not xs:
        return r
    a = (xs[0] - p) // 4 * 4 + p
    b = (xs[-1] + 4 - p) // 4 * 4 + p
    return r[:a] + r[a:b].replace(".", "G") + r[b:]


def fit(views, p):
    """The views in pairs from p, cut to the box: (pixels drawn, arts, rows)."""
    views = [[pairs(r, p) for r in v] for v in views]
    used = [i for v in views for i, r in enumerate(v) if r.strip(".")]
    top, bottom = min(used), max(used)
    xs = [i for v in views for r in v for i, c in enumerate(r) if c != "."]
    half = max(MID - min(xs), max(xs) + 1 - MID)
    half += (MID - half - p) % 4                    # the box's edge on a pair
    arts = [[r[MID - half:MID + half] for r in v[top:bottom + 1]] for v in views]
    return sum(len(r.strip(".")) for a in arts for r in a), arts, (top, bottom)


def main():
    straight = outline(lone(cells(os.path.join(SRC, "car_0.png"))))
    left = outline(lone(cells(os.path.join(SRC, "car_left.png"))))
    drawn, arts, (top, bottom) = min(fit((straight, left), p) for p in (0, 2))
    for art in arts:
        for r in art:
            assert "." not in r.strip("."), r

    lines = ['"""Generated by tools/mkcar.py from assets/car/*.png - do not edit.',
             "",
             "The player's car seen from behind, straight and turning left: rows of",
             "mode 0 pixels, letters as scene.py CAR_PEN, '.' none.", '"""', ""]
    for name, art in (("CAR_ART", arts[0]), ("CAR_ART_LEFT", arts[1])):
        lines.append("%s = [" % name)
        lines += ['    "%s",' % r for r in art]
        lines.append("]")
        lines.append("")
    path = os.path.join(ROOT, "tools", "carart.py")
    open(path, "w").write("\n".join(lines))
    print("car: %d x %d pixels (renders' rows %d-%d), %d pixels drawn"
          % (len(arts[0][0]), len(arts[0]), top, bottom, drawn))


if __name__ == "__main__":
    main()
