#!/usr/bin/env python3
"""The driving's numbers, as Out Run's (tools/outrun.py; scene.py's car
stats): src/gen/driveq.asm - the steering's, the curves' and the engine's
constants (game.asm steer, speed_player) - and src/gen/drive.asm - the cars'
stats (init.asm car_setup), the tables by curve level, and acc_tab (the
first car's: CARn.BIN puts the picked one's - tools/mkbush.py cars_asm).

    python3 tools/mkdrive.py
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import outrun as OR  # noqa: E402
import scene as S  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def per_vsync(kmh_a_second):
    """km/h a second, Out Run's, as 8.8 depth units a VSYNC (SPEED_TOP 293)."""
    return round(kmh_a_second * S.SPEED_TOP / OR.V_TOP / OR.VSYNCS)


def defb(label, vals):
    out = [label] if label else []
    for i in range(0, len(vals), 16):
        out.append("    defb " + ",".join(str(v) for v in vals[i:i + 16]))
    return out


def main():
    slow_f = round(2048 * 128 / S.STEER_SPEED)
    assert (S.STEER_SPEED // 8) * slow_f * 2 < 0x10000
    pulls = OR.pull_levels()
    lines = [
        ";; Generated by tools/mkdrive.py - do not edit.",
        ";; The driving: Out Run's (tools/outrun.py), the first car's its own and",
        ";; the others' by their bars (scene.py CAR_LEVELS). Speeds 8.8 depth",
        ";; units a VSYNC (SPEED_TOP: Out Run's 293 km/h); moves 8.8 pairs a",
        ";; picture (Out Run's 108 units from the road's middle to its edge are",
        ";; OFFROAD_X, 20 pairs; its 12 loops a second our 25 pictures).",
        "SPEED_TOP   EQU #%04X  ; the first car's top speed: 293 km/h" % S.SPEED_TOP,
        "STEER_SPEED EQU #%04X  ; 128 km/h: slower, on the road, the wheel moves"
        % S.STEER_SPEED,
        "                       ; the car as much less (Out Run: x v / 128)",
        "SLOW_F      EQU %d    ; (speed / 8) x this x 2 / 256: speed x 256 /"
        % slow_f,
        "                       ; STEER_SPEED",
        "SHARP_S16   EQU %d     ; speed / 16 at 147 km/h: faster, in a curve of"
        % S.SHARP_S16,
        "                       ; level 5-7 the wheel moves the car less (sharp_tab)",
        "WHEEL_RAMP  EQU %d     ; the most the wheel turns a picture (Out Run: 64"
        % round(64 * OR.LOOPS / OR.PICTURES),
        "                       ; of 127 a loop)",
        "PUSH_RAMP   EQU %d     ; the most a curve's push changes a picture (5"
        % round(5 * OR.LOOP_TO_PIC * OR.LOOPS / OR.PICTURES * 256),
        "                       ; units a loop a loop)",
        "SAND_W      EQU %d      ; pairs of sand off the road's edge (Out Run's 40"
        % S.SAND_W,
        "                       ; units), the grass past it",
        "SPEED_COAST EQU %d      ; neither faster nor slower: down a VSYNC (48 km/h"
        % per_vsync(OR.ENGINE_STEPS * 2),
        "                       ; a second, 2 an engine step)",
        "SPEED_BRK   EQU %d     ; slower: down a VSYNC (~%d km/h a second)"
        % (per_vsync(OR.brake_rate()), OR.brake_rate()),
        "SPEED_DRAG  EQU %d      ; over the sand's or the grass's most: down a VSYNC"
        % per_vsync(OR.ENGINE_STEPS * 2),
        "ACC_N       EQU %d     ; acc_tab's entries a gear, by speed / %d"
        % (S.ACC_N, S.ACC_BAND),
        "SHIFT_SPEED EQU #%04X  ; the demo's drive: HIGH from %d km/h on, LOW under"
        % (S.SHIFT_SPEED, OR.ENGINE_SHIFT),
        "    ASSERT SPEED_TOP < (ACC_N*%d)" % S.ACC_BAND]
    open(os.path.join(ROOT, "src", "gen", "driveq.asm"), "w").write("\n".join(lines) + "\n")
    lines = [
        ";; Generated by tools/mkdrive.py - do not edit.",
        ";; The driving's tables (its numbers: gen/driveq.asm).",
        ";; per car: the most it goes in LOW and in HIGH, on the road (its top",
        ";; speeds: Out Run's 193 and 293 km/h), on the sand (193, 221) and on the",
        ";; grass past it (117, 88) - speed_player's sp_caps - then the steering's",
        ";; and the curves' factors k and m (game.asm steer)",
        "car_stats"]
    for c, (sp, ac, gr) in enumerate(S.CAR_LEVELS):
        lines += ["    defw " + ",".join("#%04X" % v for v in S.car_caps(c))
                  + "   ; %s: speed %d, acceleration %d, grip %d" % (S.CARS[c], sp, ac, gr),
                  "    defb %d,%d" % (S.car_steer_k(c), S.car_push_m(c))]
    lines += ["CAR_STATS_LEN EQU 14  ; bytes a car", ""]
    lines += [";; per curve level 1-7: Out Run's pull for the radius it stands for",
              ";; (%s): k, the push s x m x k / 8192 (game.asm steer)"
              % ", ".join(str(OR.radius(L)) for L in range(1, 8))]
    lines += defb("push_levels", pulls)
    lines += ["    ASSERT hi(push_levels-1) == hi(push_levels+6)",
              ";; per curve level 0-7: the steering's cut from SHARP_S16 on - (speed /",
              ";; 16 - SHARP_S16) x this / 256 is the cut, /256 of the turn (Out Run: a",
              ";; bend under r 64, (v - 147)(64 - r) / 9408)"]
    lines += defb("sharp_tab", [0] + OR.sharp_levels())
    lines += ["    ASSERT hi(sharp_tab) == hi(sharp_tab+7)",
              ";; the speed gained a VSYNC faster held, sixteenths of a unit, by speed /",
              ";; %d, in LOW then in HIGH (speed_acc): the first car's - CARn.BIN puts"
              % S.ACC_BAND, ";; the picked one's"]
    lines += defb("acc_tab", S.car_acc(0))
    lines += ["    ASSERT $-acc_tab == 2*ACC_N"]
    open(os.path.join(ROOT, "src", "gen", "drive.asm"), "w").write("\n".join(lines) + "\n")
    print("drive: full lock %s pairs a picture; pull by level %s; COAST %d BRK %d"
          % ("/".join("%.2f" % (127 * S.car_steer_k(c) / 64 / 256) for c in range(4)),
             pulls, per_vsync(48), per_vsync(OR.brake_rate())))


if __name__ == "__main__":
    main()
