#!/usr/bin/env python3
"""The driving's numbers (scene.py's car stats; the gears Out Run's,
tools/outrun.py): src/gen/driveq.asm - the steering's, the curves', the
drag's, the hills', the grass's and the engine's constants (game.asm
steer, speed_player) - and src/gen/drive.asm - the cars' stats (init.asm
car_setup), the tables by curve level and by speed, and acc_tab (the
first car's: CARn.BIN puts the picked one's - tools/mkbush.py cars_asm).

    python3 tools/mkdrive.py
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import course as C  # noqa: E402
import outrun as OR  # noqa: E402
import scene as S  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def per_vsync(kmh_a_second):
    """km/h a second as 8.8 depth units a VSYNC (SPEED_TOP 293), whole."""
    return round(S.per_vsync(kmh_a_second))


def defb(label, vals):
    out = [label] if label else []
    for i in range(0, len(vals), 16):
        out.append("    defb " + ",".join(str(v) for v in vals[i:i + 16]))
    return out


def main():
    slow_f = round(2048 * 128 / S.STEER_SPEED)
    assert (S.STEER_SPEED // 8) * slow_f * 2 < 0x10000
    hill_kmhs = S.hill_speed(S.HILL_MOST) * OR.PICTURES / S.per_vsync(1) / OR.VSYNCS
    assert 0 < S.HILL_F < 256
    assert all(abs(h) <= S.HILL_MOST for segs in [C.DEMO] + [st["segs"] for st in C.STAGES]
               for h, k in C.entries(segs))        # (game.asm hill_speed: a byte)
    # the gears cross where the demo's drive changes up (Out Run's 160)
    assert S.engine_pull(0, OR.ENGINE_SHIFT - 8) > S.engine_pull(1, OR.ENGINE_SHIFT - 8)
    assert S.engine_pull(0, OR.ENGINE_SHIFT + 8) < S.engine_pull(1, OR.ENGINE_SHIFT + 8)
    drag = S.drag_tab()
    lines = [
        ";; Generated by tools/mkdrive.py - do not edit.",
        ";; The driving (tools/scene.py; the gears Out Run's, tools/outrun.py):",
        ";; the first car's and the others' by their bars (CAR_LEVELS). Speeds 8.8",
        ";; depth units a VSYNC (SPEED_TOP: 293 km/h); moves 8.8 pairs a picture.",
        "SPEED_TOP   EQU #%04X  ; the first car's top speed: 293 km/h" % S.SPEED_TOP,
        "STEER_SPEED EQU #%04X  ; 128 km/h: slower, the wheel moves the car as"
        % S.STEER_SPEED,
        "                       ; much less (none standing)",
        "SLOW_F      EQU %d    ; (speed / 8) x this x 2 / 256: speed x 256 /"
        % slow_f,
        "                       ; STEER_SPEED",
        "WHEEL_RAMP  EQU %d     ; the most the wheel turns a picture (Out Run: 64"
        % round(64 * OR.LOOPS / OR.PICTURES),
        "                       ; of 127 a loop)",
        "PUSH_RAMP   EQU %d     ; the most a curve's push changes a picture"
        % round(5 * OR.LOOP_TO_PIC * OR.LOOPS / OR.PICTURES * 256),
        "SLIDE_V     EQU %d    ; the push the tyres slip from: they squeal and"
        % S.SLIDE_V,
        "                       ; take speed (%.2f of the first car's full lock)" % S.SLIDE,
        "SAND_W      EQU %d      ; pairs of sand off the road's edge (Out Run's 40"
        % S.SAND_W,
        "                       ; units), the grass past it",
        "SPEED_BRK   EQU %d     ; slower: down a VSYNC over the air's drag"
        % per_vsync(S.BRAKE_KMHS),
        "                       ; (drag_tab) - %d km/h a second more" % S.BRAKE_KMHS,
        "SPEED_STOP  EQU %d     ; the game's own braking - the time up, the demo's,"
        % per_vsync(S.STOP_KMHS),
        "                       ; before the start (~%d km/h a second)" % S.STOP_KMHS,
        "SPEED_COAST EQU %d      ; the demo's drive lifting off: down a VSYNC"
        % per_vsync(OR.ENGINE_STEPS * 2),
        "SPEED_DRAG  EQU %d      ; over the sand's or the grass's most: down a VSYNC"
        % per_vsync(OR.ENGINE_STEPS * 2),
        "BACK_SPEED  EQU #%04X  ; a crash over, the car drives back to the road's"
        % S.BACK_SPEED,
        "                       ; middle no faster",
        "HILL_F      EQU %d     ; a hill gives the speed |hill| x this / 256 units a"
        % S.HILL_F,
        "                       ; picture - a crest more, a dip less: %d on the"
        % S.hill_speed(S.HILL_MOST),
        "                       ; steepest (%d), %.1f km/h a second" % (S.HILL_MOST, hill_kmhs),
        "GRASS_RAMP  EQU %d     ; the most the wheel turns a picture on the grass,"
        % S.GRASS_RAMP,
        "                       ; where it moves the car half as far",
        "GRASS_BRK   EQU %d      ; SPEED_BRK there" % round(per_vsync(S.BRAKE_KMHS) * S.GRASS_BRAKE),
        "ACC_N       EQU %d     ; acc_tab's entries a gear, by speed / %d"
        % (S.ACC_N, S.ACC_BAND),
        "SHIFT_SPEED EQU #%04X  ; the demo's drive: HIGH from %d km/h on, LOW under"
        % (S.SHIFT_SPEED, OR.ENGINE_SHIFT),
        "    ASSERT SPEED_TOP < (ACC_N*%d) && lo(BACK_SPEED) == 0" % S.ACC_BAND]
    open(os.path.join(ROOT, "src", "gen", "driveq.asm"), "w").write("\n".join(lines) + "\n")
    lines = [
        ";; Generated by tools/mkdrive.py - do not edit.",
        ";; The driving's tables (its numbers: gen/driveq.asm).",
        ";; per car: the most it goes in LOW and in HIGH, on the road (its top",
        ";; speeds: Out Run's 193 and 293 km/h), on the sand (193, 221) and on the",
        ";; grass past it (117, 88) - speed_player's sp_caps - then the steering's",
        ";; and the curves' factors k and m (game.asm steer)",
        "car_stats"]
    for c, (sp, ac, gr) in enumerate(S.CAR_LEVELS):
        lines += ["    defw " + ",".join("#%04X" % v for v in S.car_caps(c))
                  + "   ; %s: speed %d, acceleration %d, grip %d" % (S.CARS[c], sp, ac, gr),
                  "    defb %d,%d" % (S.car_steer_k(c), S.car_push_m(c))]
    lines += ["CAR_STATS_LEN EQU 14  ; bytes a car", ""]
    lines += [";; per curve level 1-7: the push with the curvature - (speed / 16)^2 / 256",
              ";; x m x this / 256 pairs a picture (game.asm steer): the first car",
              ";; holds level 7 at the full lock up to %d km/h" % S.GRIP_V7]
    lines += defb("push_levels", S.PUSH_K)
    lines += ["    ASSERT hi(push_levels-1) == hi(push_levels+6)",
              ";; the air's drag: units a VSYNC slower off the pedal, by speed / 256",
              ";; (%d km/h a second standing, %d at SPEED_TOP, by the speed squared)"
              % S.DRAG_KMHS]
    lines += defb("drag_tab", drag)
    lines += ["    ASSERT hi(drag_tab) == hi(drag_tab+%d)" % (len(drag) - 1),
              ";; the speed gained a VSYNC faster held, sixteenths of a unit, by speed /",
              ";; %d, in LOW then in HIGH (speed_acc; scene.py ENGINE): the first car's -"
              % S.ACC_BAND, ";; CARn.BIN puts the picked one's"]
    lines += defb("acc_tab", S.car_acc(0))
    lines += ["    ASSERT $-acc_tab == 2*ACC_N"]
    open(os.path.join(ROOT, "src", "gen", "drive.asm"), "w").write("\n".join(lines) + "\n")
    hold = lambda c, L: S.GRIP_V7 * (7 / L * (S.car_steer_k(c) / S.STEER_K0) * (S.PUSH_M0 / S.car_push_m(c))) ** 0.5
    print("drive: full lock %s pairs a picture; drag %s, brake %d more"
          % ("/".join("%.2f" % (127 * S.car_steer_k(c) / 64 / 256) for c in range(4)),
             drag, per_vsync(S.BRAKE_KMHS)))
    for c in range(4):
        print("  %s holds levels 1-7 up to %s km/h" % (
            S.CARS[c], " ".join("%.0f" % hold(c, L) for L in range(1, 8))))
    top = lambda c: OR.V_TOP * S.TOP_SPEED[S.CAR_LEVELS[c][0]] / S.SPEED_TOP
    for c in range(4):
        t = lambda v, **k: S.time_to(c, v * top(c) / OR.V_TOP, **k)
        sh = OR.ENGINE_SHIFT * top(c) / OR.V_TOP
        print("  %s (top %.0f km/h): 100 km/h at %.1f s, its 160 at %.1f, 193 at %.1f, 250 at"
              " %.1f, 280 at %.1f; in HIGH alone its 100 at %.1f, 250 at %.1f" % (
                  S.CARS[c], top(c), S.time_to(c, 100, gear=0), t(160, gear=0), t(193, shift=sh),
                  t(250, shift=sh), t(280, shift=sh), t(100, gear=1), t(250, gear=1)))
    steps = [next(h for h in range(128) if S.hill_speed(h) >= n)
             for n in range(1, S.hill_speed(S.HILL_MOST) + 1)]
    print("  a hill: up to %+d units a picture (%.1f km/h a second), a unit more from %s;"
          " on the grass the wheel %d a picture, the brake %d"
          % (S.hill_speed(S.HILL_MOST), hill_kmhs, "/".join(map(str, steps)), S.GRASS_RAMP,
             round(per_vsync(S.BRAKE_KMHS) * S.GRASS_BRAKE)))


if __name__ == "__main__":
    main()
