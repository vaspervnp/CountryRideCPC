#!/usr/bin/env python3
"""Generate the constants and the HUD/horizon graphics.

    src/gen/consts.asm   palette, pen bytes, screen and road geometry
    src/gen/gfx.asm      HUD glyphs, labels, gauge colours, sky, mountains

Both are committed, so a build needs only rasm; python3 (with Pillow for the
mock-up only) is needed when the art changes.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cpcgfx as G
import scene as S

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def encode_rows(pens_rows):
    """Pen rows (even widths) to mode 0 byte rows."""
    out = []
    for row in pens_rows:
        assert len(row) % 2 == 0, len(row)
        out.append([G.m0_byte(row[i], row[i + 1]) for i in range(0, len(row), 2)])
    return out


def defb_rows(emit, rows, per_line=16):
    flat = [b for r in rows for b in r]
    for i in range(0, len(flat), per_line):
        emit("    defb " + ",".join("#%02X" % b for b in flat[i:i + per_line]))


def pad_even(rows, bg=S.HUD_BG):
    if len(rows[0]) % 2:
        rows = [r + [bg] for r in rows]
    return rows


def consts():
    lines = [";; Generated by tools/mkgfx.py - do not edit.", ""]
    emit = lines.append
    emit(";; pens")
    for i, (name, fw) in enumerate(G.PENS):
        emit("PEN_%-10s EQU %2d   ; firmware colour %d" % (name, i, fw))
    emit("")
    emit(";; a byte of two pixels of the same pen")
    for i, (name, _) in enumerate(G.PENS):
        emit("SOLID_%-10s EQU #%02X" % (name, G.m0_solid(i)))
    emit("")
    emit(";; screen and road geometry")
    for name in ("SCR_W", "SCR_BYTES", "SCR_H", "TOP_ROWS", "HUD_H",
                 "MOUNT_BOTTOM", "ROAD_TOP_MIN", "ROAD_TOP_MAX", "ROAD_LINES",
                 "ROWS", "HORIZON_Y", "HALF_MAX", "BAND_SHIFT", "FAR_Z"):
        emit("%-13s EQU %d" % (name, getattr(G, name)))
    far = max(r for r in range(1, G.ROWS + 1) if G.row_depth(r) > G.FAR_Z)
    emit("FAR_ROW       EQU %d   ; rows 1..FAR_ROW are past FAR_Z" % far)
    emit("MOUNT_TOP     EQU %d   ; first line of the mountain strip"
         % S.mountains_top())
    emit("")
    emit("BORDER_HW     EQU #%02X" % (0x40 + G.FIRMWARE[G.BORDER_FW][0]))
    return lines


def consts_data():
    return [";; Generated by tools/mkgfx.py - do not edit.", "",
            ";; palette: Gate Array colour bytes (#40 + hardware colour), pens 0..15",
            "palette_hw",
            "    defb " + ",".join("#%02X" % (0x40 + G.pen_hw(i)) for i in range(16))]


def gfx():
    lines = [";; Generated by tools/mkgfx.py - do not edit.",
             ";; Everything here is drawn on the HUD's own background pen, so",
             ";; it is copied to the screen, never masked.", ""]
    emit = lines.append

    # big glyphs: 4 bytes x 18 lines
    names = [str(d) for d in range(10)] + ["N"]
    emit(";; big glyphs, 4 bytes x 18 lines: 0-9 then N (gear neutral)")
    emit("BIG_W EQU 4")
    emit("BIG_H EQU 18")
    emit("big_glyphs")
    for n in names:
        emit("; " + n)
        defb_rows(emit, encode_rows(S.big_glyph(n)))
    emit("")

    emit(";; small digits, 3 bytes x 8 lines")
    emit("SMALL_W EQU 3")
    emit("SMALL_H EQU 8")
    emit("small_digits")
    for d in range(10):
        emit("; %d" % d)
        defb_rows(emit, encode_rows(S.small_digit(d)))
    emit("")

    # labels: width in bytes, 8 lines
    emit(";; labels: defb width in bytes, then 8 lines of bytes")
    labels = [("lbl_time", "TIME", S.LABEL_PEN), ("lbl_speed", "SPEED", S.LABEL_PEN),
              ("lbl_total", "TOTAL TIME", S.LABEL_PEN), ("lbl_fuel", "FUEL", S.LABEL_PEN),
              ("lbl_apos", "'", S.VALUE_PEN), ("lbl_quote", '"', S.VALUE_PEN)]
    widths = {}
    for name, text, pen in labels:
        rows = pad_even(S.small_text(text, pen))
        enc = encode_rows(rows)
        widths[name] = len(enc[0])
        emit("%s" % name)
        emit("    defb %d" % len(enc[0]))
        defb_rows(emit, enc)
    emit("")

    # HUD positions, in bytes and lines
    H = S.HUD
    sp = S.small_text("SPEED")
    speed_x = (G.SCR_W - len(sp[0])) // 2 // 2 * 2
    pos = dict(
        TIME_LBL=H["time_label"], TIME_VAL=H["time_value"],
        SPEED_LBL=(speed_x, H["speed_label"][1]), SPEED_GAUGE=H["speed_gauge"],
        GEAR=H["gear"], TOTAL_LBL=H["total_label"], TOTAL_VAL=H["total_value"],
        FUEL_LBL=H["fuel_label"], FUEL_GAUGE=H["fuel_gauge"])
    emit(";; HUD layout: x in bytes, y in lines")
    for k, (x, y) in pos.items():
        assert x % 2 == 0, k
        emit("%s_X EQU %d" % (k, x // 2))
        emit("%s_Y EQU %d" % (k, y))
    emit("GAUGE_SEGS EQU %d" % S.GAUGE_SEGS)
    emit("GAUGE_H    EQU %d" % S.GAUGE_H)
    # total time m'ss"cc: digit x offsets (bytes) and separator positions
    emit(";; total time m'ss\"cc: byte offsets of the six digits and two marks")
    xs = []
    marks = []
    x = 0
    for ch in "0'00\"00":
        if ch.isdigit():
            xs.append(x // 2)
            x += 6
        else:
            marks.append(x // 2)
            x += 4 if ch == "'" else 6
    emit("total_digit_x")
    emit("    defb " + ",".join(str(v) for v in xs))
    emit("TOTAL_APOS_X  EQU %d" % marks[0])
    emit("TOTAL_QUOTE_X EQU %d" % marks[1])
    emit("")

    # gauges: per segment the pair of bytes (3 lit pixels + 1 background)
    emit(";; gauge segments: two bytes per segment, by segment index")
    for name, rev in (("fuel_seg", False), ("speed_seg", True)):
        emit(name)
        for s in range(S.GAUGE_SEGS):
            zone = s * 4 // S.GAUGE_SEGS
            pen = S.GAUGE_ZONES[3 - zone] if rev else S.GAUGE_ZONES[zone]
            emit("    defb #%02X,#%02X" % (G.m0_byte(pen, pen),
                                         G.m0_byte(pen, S.HUD_BG)))
    emit("SEG_OFF0 EQU #%02X" % G.m0_byte(G.PEN["BLACK"], G.PEN["BLACK"]))
    emit("SEG_OFF1 EQU #%02X" % G.m0_byte(G.PEN["BLACK"], S.HUD_BG))
    emit("")

    # sky: per line from HUD_H to MOUNT_TOP-1, a 2-byte repeating pattern
    top = S.mountains_top()
    emit(";; sky lines %d..%d: the two bytes that repeat across each line" %
         (G.HUD_H, top - 1))
    emit("sky_pairs")
    for y in range(G.HUD_H, top):
        p = [S.sky_pen(x, y) for x in range(4)]
        emit("    defb #%02X,#%02X" % (G.m0_byte(p[0], p[1]), G.m0_byte(p[2], p[3])))
    emit("")

    # the screen address of every line, buffer 0 (RAM_C1); buffer 1 is the
    # same for the top half (with RAM_C3) and #8000 lower for the bottom half
    emit(";; CPU address of each of the 272 lines, buffer 0 with RAM_C1")
    emit("line_tab")
    for y in range(G.SCR_H):
        row, ras = y >> 3, y & 7
        if row < G.TOP_ROWS:
            a = 0x4080 + ras * 0x800 + row * 96
        else:
            a = 0x8000 + ras * 0x800 + (row - G.TOP_ROWS) * 96
        emit("    defw #%04X   ; %d" % (a, y))
    emit("")

    # a hill profile for the demo: indexed by (zcam / 32) mod 256
    import math
    prof = []
    for i in range(256):
        seg, t = divmod(i, 64)
        if seg == 0:
            v = 0 if t < 16 else 95 * math.sin(math.pi * (t - 16) / 48)
        elif seg == 1:
            v = 0 if t < 16 else -90 * math.sin(math.pi * (t - 16) / 48)
        elif seg == 2:
            v = 0 if t < 8 else 60 * math.sin(math.pi * (t - 8) / 56)
        else:
            v = 0 if t < 16 else 95 * math.sin(math.pi * (t - 16) / 48)
        prof.append(int(round(v)) & 0xFF)
    emit(";; demo hill profile, (zcam / 32) mod 256 -> hill")
    emit("hill_profile")
    for i in range(0, 256, 16):
        emit("    defb " + ",".join("#%02X" % v for v in prof[i:i + 16]))
    emit("")

    # mountains: the first 192 pixels of the panorama, raw
    t, rows = S.horizon_panorama()
    assert t == top
    emit(";; mountain strip, lines %d..%d, 96 bytes each" % (top, G.MOUNT_BOTTOM - 1))
    emit("mountains")
    defb_rows(emit, encode_rows([r[:G.SCR_W] for r in rows]))
    return lines


def main():
    gen = os.path.join(ROOT, "src", "gen")
    os.makedirs(gen, exist_ok=True)
    open(os.path.join(gen, "consts.asm"), "w").write("\n".join(consts()) + "\n")
    open(os.path.join(gen, "consts_data.asm"), "w").write("\n".join(consts_data()) + "\n")
    open(os.path.join(gen, "gfx.asm"), "w").write("\n".join(gfx()) + "\n")
    print("src/gen/consts.asm, src/gen/gfx.asm written")


if __name__ == "__main__":
    main()
