#!/usr/bin/env python3
"""Generate the constants and the HUD/horizon graphics.

    src/gen/consts.asm   palette, pen bytes, screen and road geometry
    src/gen/gfx.asm      HUD glyphs, labels, gauge colours, sky, mountains

Both are committed, so a build needs only rasm; python3 (with Pillow for the
mock-up only) is needed when the art changes.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cpcgfx as G
import scene as S

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def encode_rows(pens_rows):
    """Pen rows (even widths) to mode 0 byte rows."""
    out = []
    for row in pens_rows:
        assert len(row) % 2 == 0, len(row)
        out.append([G.m0_byte(row[i], row[i + 1]) for i in range(0, len(row), 2)])
    return out


def defb_rows(emit, rows, per_line=16):
    flat = [b for r in rows for b in r]
    for i in range(0, len(flat), per_line):
        emit("    defb " + ",".join("#%02X" % b for b in flat[i:i + per_line]))


def pad_even(rows, bg=S.HUD_BG):
    if len(rows[0]) % 2:
        rows = [r + [bg] for r in rows]
    return rows


def consts():
    lines = [";; Generated by tools/mkgfx.py - do not edit.", ""]
    emit = lines.append
    emit(";; pens")
    for i, (name, fw) in enumerate(G.PENS):
        emit("PEN_%-10s EQU %2d   ; firmware colour %d" % (name, i, fw))
    emit("")
    emit(";; a byte of two pixels of the same pen")
    for i, (name, _) in enumerate(G.PENS):
        emit("SOLID_%-10s EQU #%02X" % (name, G.m0_solid(i)))
    emit("")
    emit(";; screen and road geometry")
    for name in ("SCR_W", "SCR_BYTES", "SCR_H", "TOP_ROWS", "HUD_H",
                 "SKY_Y", "BLOCK_BOTTOM", "ROAD_Y", "ROAD_TOP_MIN", "ROAD_TOP_MAX",
                 "ROAD_END", "ROAD_LINES", "ROWS", "NEAR_ROW", "HORIZON_Y",
                 "HALF_MAX", "MIN_HALF",
                 "BAND_SHIFT", "FAR_Z"):
        emit("%-13s EQU %d" % (name, getattr(G, name)))
    far = max(r for r in range(1, G.ROWS + 1) if G.row_depth(r) > G.FAR_Z)
    emit("FAR_ROW       EQU %d   ; rows 1..FAR_ROW are past FAR_Z" % far)
    emit("MOUNT_TOP     EQU %d   ; first line of the mountain strip"
         % S.mountains_top())
    emit("PANO_Y0       EQU %d   ; first line of the panorama (a character row)"
         % S.pano_y0())
    emit("PANO_WORDS    EQU %d   ; panorama width in CRTC words (4 pixels)"
         % S.PANO_WORDS)
    emit("ROAD_AREA_Y   EQU %d   ; first line of the road part's memory"
         % S.ROAD_AREA_Y)
    emit("LAST_Y        EQU %d   ; the road's last line, from ROAD_AREA_Y"
         % (G.ROAD_END - 1 - S.ROAD_AREA_Y))
    emit("")
    emit("BORDER_HW     EQU #%02X" % (0x40 + G.FIRMWARE[G.BORDER_FW][0]))
    emit(";; the border where the ruptures show it: above the sky, below the")
    emit(";; mountains")
    emit("BORDER_TOP_HW EQU #%02X" % (0x40 + G.pen_hw(S.BORDER_TOP)))
    emit("BORDER_LOW_HW EQU #%02X" % (0x40 + G.pen_hw(S.BORDER_LOW)))
    emit("SOLID_GROUND  EQU #%02X" % G.m0_solid(G.GROUND_PEN))
    return lines


def consts_data():
    return [";; Generated by tools/mkgfx.py - do not edit.", "",
            ";; palette: Gate Array colour bytes (#40 + hardware colour), pens 0..15",
            "palette_hw",
            "    defb " + ",".join("#%02X" % (0x40 + G.pen_hw(i)) for i in range(16))]


def gfx():
    lines = [";; Generated by tools/mkgfx.py - do not edit.",
             ";; Everything here is drawn on the HUD's own background pen, so",
             ";; it is copied to the screen, never masked.", ""]
    emit = lines.append

    # big glyphs: 4 bytes x 18 lines
    names = [str(d) for d in range(10)] + ["N"]
    emit(";; big glyphs, 4 bytes x 18 lines: 0-9 then N (gear neutral)")
    emit("BIG_W EQU 4")
    emit("BIG_H EQU 18")
    emit("big_glyphs")
    for n in names:
        emit("; " + n)
        defb_rows(emit, encode_rows(S.big_glyph(n)))
    emit("")

    emit(";; small glyphs, 3 bytes x 8 lines: the digits 0-9, then the space")
    emit(";; and the letters of the messages (scene.py MSG_GLYPHS)")
    emit("SMALL_W EQU 3")
    emit("SMALL_H EQU 8")
    emit("small_digits")
    for ch in S.MSG_GLYPHS:
        emit("; %s" % ch)
        defb_rows(emit, encode_rows(S.small_glyph(ch)))
    emit("")

    # the messages: MSG_W glyph numbers each, centred
    emit(";; the HUD's messages (scene.py MESSAGES), MSG_W glyphs each")
    emit("MSG_W EQU %d" % S.MSG_W)
    emit("MSG_X EQU %d" % (S.MSG_X // 2))
    emit("MSG_Y EQU %d" % S.HUD["message"][1])
    emit("MSG_SPACE EQU %d" % S.MSG_GLYPHS.index(" "))
    for n, m in enumerate(S.MESSAGES):
        name = "MSG_" + (m.replace(" ", "_").strip("!") if m else "NONE")
        emit("%-17s EQU %d" % (name, n))
    emit("msg_texts")
    for n in range(len(S.MESSAGES)):
        emit("    defb " + ",".join(str(v) for v in S.msg_cells(n)) + "   ; " + S.MESSAGES[n])
    emit("")

    # labels: width in bytes, 8 lines
    emit(";; labels: defb width in bytes, then 8 lines of bytes")
    labels = [("lbl_time", "TIME", S.LABEL_PEN), ("lbl_speed", "SPEED", S.LABEL_PEN),
              ("lbl_total", "TOTAL TIME", S.LABEL_PEN), ("lbl_cp", "CHECKPOINT", S.LABEL_PEN),
              ("lbl_apos", "'", S.VALUE_PEN), ("lbl_quote", '"', S.VALUE_PEN)]
    widths = {}
    for name, text, pen in labels:
        rows = pad_even(S.small_text(text, pen))
        enc = encode_rows(rows)
        widths[name] = len(enc[0])
        emit("%s" % name)
        emit("    defb %d" % len(enc[0]))
        defb_rows(emit, enc)
    emit("")

    # HUD positions, in bytes and lines
    H = S.HUD
    sp = S.small_text("SPEED")
    speed_x = (G.SCR_W - len(sp[0])) // 2 // 2 * 2
    pos = dict(
        TIME_LBL=H["time_label"], TIME_VAL=H["time_value"],
        SPEED_LBL=(speed_x, H["speed_label"][1]), SPEED_GAUGE=H["speed_gauge"],
        GEAR=H["gear"], TOTAL_LBL=H["total_label"], TOTAL_VAL=H["total_value"],
        CP_LBL=H["cp_label"], CP_GAUGE=H["cp_gauge"])
    emit(";; HUD layout: x in bytes, y in lines")
    for k, (x, y) in pos.items():
        assert x % 2 == 0, k
        emit("%s_X EQU %d" % (k, x // 2))
        emit("%s_Y EQU %d" % (k, y))
    emit("GAUGE_SEGS EQU %d" % S.GAUGE_SEGS)
    emit("GAUGE_H    EQU %d" % S.GAUGE_H)
    # total time m'ss"cc: digit x offsets (bytes) and separator positions
    emit(";; total time m'ss\"cc: byte offsets of the six digits and two marks")
    xs = []
    marks = []
    x = 0
    for ch in "0'00\"00":
        if ch.isdigit():
            xs.append(x // 2)
            x += 6
        else:
            marks.append(x // 2)
            x += 4 if ch == "'" else 6
    emit("total_digit_x")
    emit("    defb " + ",".join(str(v) for v in xs))
    emit("TOTAL_APOS_X  EQU %d" % marks[0])
    emit("TOTAL_QUOTE_X EQU %d" % marks[1])
    emit("")

    # gauges: per segment the pair of bytes (3 lit pixels + 1 background)
    emit(";; gauge segments: two bytes per segment, by segment index")
    for name, rev in (("cp_seg", False), ("speed_seg", True)):
        emit(name)
        for s in range(S.GAUGE_SEGS):
            zone = s * 4 // S.GAUGE_SEGS
            pen = S.GAUGE_ZONES[3 - zone] if rev else S.GAUGE_ZONES[zone]
            emit("    defb #%02X,#%02X" % (G.m0_byte(pen, pen),
                                         G.m0_byte(pen, S.HUD_BG)))
    emit("SEG_OFF0 EQU #%02X" % G.m0_byte(G.PEN["BLACK"], G.PEN["BLACK"]))
    emit("SEG_OFF1 EQU #%02X" % G.m0_byte(G.PEN["BLACK"], S.HUD_BG))
    emit("")

    # sky: per line from SKY_Y to the panorama, a 2-byte repeating pattern
    top = S.mountains_top()
    emit(";; sky lines %d..%d: the two bytes that repeat across each line" %
         (G.SKY_Y, S.pano_y0() - 1))
    emit("sky_pairs")
    for y in range(G.SKY_Y, S.pano_y0()):
        p = [S.sky_pen(x, y) for x in range(4)]
        emit("    defb #%02X,#%02X" % (G.m0_byte(p[0], p[1]), G.m0_byte(p[2], p[3])))
    emit("")

    # where every line is (hw.asm has the plan)
    emit(";; CPU address of each of the 272 lines: the HUD (0-%d) in page 1"
         % (G.HUD_H - 1))
    emit(";; with RAM_C1, buffer 0 (buffer 1's is HUD1_OFF on); the road part's")
    emit(";; memory (%d-271) in page 2 with RAM_C1, buffer 0 (buffer 1's is"
         % S.ROAD_AREA_Y)
    emit(";; #8000 lower); the lines between nowhere (the sky part is the ring:")
    emit(";; ring_col)")
    emit("line_tab")
    for y in range(G.SCR_H):
        row, ras = y >> 3, y & 7
        if y < G.HUD_H:
            a = 0x4000 + ras * 0x800 + row * 96
        elif y < S.ROAD_AREA_Y:
            a = 0
        else:
            a = 0x8000 + ras * 0x800 + (row - S.ROAD_AREA_Y // 8) * 96
        emit("    defw #%04X   ; %d" % (a, y))
    emit("")

    # The demo's track, indexed by (zcam / 32) mod 256: stretches of flat
    # straight road, hills (a crest ahead is positive, a dip negative) and
    # curves, one at a time - the road never bends on a hill. A curve moves
    # one level an entry towards its level and back, so the road bends into
    # it and out of it.
    import math
    track = [("flat", 6), ("hill", 32, 95), ("flat", 4), ("curve", 30, 5),
             ("flat", 4), ("hill", 32, -90), ("flat", 4), ("curve", 30, -7),
             ("flat", 4), ("hill", 26, 60), ("flat", 4), ("curve", 20, -3),
             ("flat", 4), ("hill", 24, 95), ("flat", 4), ("curve", 28, 7)]
    hills, curve = [], []
    for kind, n, *arg in track:
        for t in range(n):
            h = k = 0
            if kind == "hill":
                h = int(round(arg[0] * math.sin(math.pi * t / n)))
            elif kind == "curve":
                k = arg[0]
                k = max(-abs(k), min(abs(k), min(t, n - 1 - t))) * (1 if k > 0 else -1)
            hills.append(h)
            curve.append(k)
    assert len(hills) == 256
    assert all(h == 0 or k == 0 for h, k in zip(hills, curve))
    assert max(map(abs, curve)) <= G.CURVE_K
    assert all(abs(a - b) <= 1 for a, b in zip(curve, curve[1:] + curve[:1]))
    emit(";; demo hill profile, (zcam / 32) mod 256 -> hill")
    emit("hill_profile")
    for i in range(0, 256, 16):
        emit("    defb " + ",".join("#%02X" % (v & 0xFF) for v in hills[i:i + 16]))
    emit("")
    emit(";; demo curve levels, (zcam / 32) mod 256 -> level (signed); must")
    emit(";; follow hill_profile")
    emit("curve_profile")
    for i in range(0, 256, 16):
        emit("    defb " + ",".join("#%02X" % (v & 0xFF) for v in curve[i:i + 16]))
    emit("")

    lines += horizon(top)
    return lines


def horizon(top):
    """The mountains: the whole panorama, from the character row they start
    in, over the sky - a column (a word wide) at a time, as ring_col writes
    them."""
    lines = []
    emit = lines.append
    t, rows = S.horizon_panorama()
    assert t == top
    y0 = S.pano_y0()
    full = [[S.sky_pen(x, y) for x in range(S.PANORAMA_W)] for y in range(y0, top)]
    full += rows
    enc = encode_rows(full)
    assert len(enc) % 8 == 0
    nrows = len(enc) // 8
    cols = [[b for row in enc for b in row[2 * c:2 * c + 2]] for c in range(S.PANO_WORDS)]
    # a column's character rows - its two bytes on each of 8 lines, top to
    # bottom: 16 bytes - are many columns' (the sky, the mountains' bodies):
    # each different one is kept once
    rows, ptrs = {}, []
    for col in cols:
        ptrs.append([rows.setdefault(tuple(col[16 * r:16 * r + 16]), len(rows))
                     for r in range(nrows)])
    emit(";; the panorama, lines %d..%d: for each of the %d words across, its"
         % (y0, G.BLOCK_BOTTOM - 1, S.PANO_WORDS))
    emit(";; %d character rows' addresses in pano_rows - each row its two bytes on"
         % nrows)
    emit(";; each of its 8 lines, top to bottom, %d different ones of %d"
         % (len(rows), nrows * S.PANO_WORDS))
    emit("PANO_COL_ROWS EQU %d" % nrows)
    emit("pano_cols")
    for p in ptrs:
        emit("    defw " + ",".join("pano_rows+%d" % (16 * i) for i in p))
    emit("pano_rows")
    defb_rows(emit, sorted(rows, key=rows.get))
    emit("")
    return lines


def main():
    gen = os.path.join(ROOT, "src", "gen")
    os.makedirs(gen, exist_ok=True)
    open(os.path.join(gen, "consts.asm"), "w").write("\n".join(consts()) + "\n")
    open(os.path.join(gen, "consts_data.asm"), "w").write("\n".join(consts_data()) + "\n")
    open(os.path.join(gen, "gfx.asm"), "w").write("\n".join(gfx()) + "\n")
    print("src/gen/consts.asm, src/gen/gfx.asm written")


if __name__ == "__main__":
    main()
