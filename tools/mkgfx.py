#!/usr/bin/env python3
"""Generate the constants and the HUD/horizon graphics.

    src/gen/consts.asm   palette, pen bytes, screen and road geometry
    src/gen/gfx.asm      HUD glyphs, labels, gauge colours, sky, mountains
    src/gen/labels.asm   the HUD's words as masks (src/labels.asm)

Both are committed, so a build needs only rasm; python3 (with Pillow for the
mock-up only) is needed when the art changes.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cpcgfx as G
import scene as S

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def encode_rows(pens_rows):
    """Pen rows (even widths) to mode 0 byte rows."""
    out = []
    for row in pens_rows:
        assert len(row) % 2 == 0, len(row)
        out.append([G.m0_byte(row[i], row[i + 1]) for i in range(0, len(row), 2)])
    return out


def defb_rows(emit, rows, per_line=16):
    flat = [b for r in rows for b in r]
    for i in range(0, len(flat), per_line):
        emit("    defb " + ",".join("#%02X" % b for b in flat[i:i + per_line]))


def pad_even(rows, bg=S.HUD_BG):
    if len(rows[0]) % 2:
        rows = [r + [bg] for r in rows]
    return rows


def consts():
    lines = [";; Generated by tools/mkgfx.py - do not edit.", ""]
    emit = lines.append
    emit(";; pens")
    for i, (name, fw) in enumerate(G.PENS):
        emit("PEN_%-10s EQU %2d   ; firmware colour %d" % (name, i, fw))
    emit("")
    emit(";; a byte of two pixels of the same pen")
    for i, (name, _) in enumerate(G.PENS):
        emit("SOLID_%-10s EQU #%02X" % (name, G.m0_solid(i)))
    emit("")
    emit(";; screen and road geometry")
    for name in ("SCR_W", "SCR_BYTES", "SCR_H", "TOP_ROWS", "HUD_H",
                 "SKY_Y", "BLOCK_BOTTOM", "ROAD_Y", "ROAD_TOP_MIN", "ROAD_TOP_MAX",
                 "ROAD_END", "ROAD_LINES", "ROWS", "NEAR_ROW", "HORIZON_Y",
                 "HALF_MAX", "MIN_HALF",
                 "BAND_SHIFT", "FAR_Z"):
        emit("%-13s EQU %d" % (name, getattr(G, name)))
    far = max(r for r in range(1, G.ROWS + 1) if G.row_depth(r) > G.FAR_Z)
    emit("FAR_ROW       EQU %d   ; rows 1..FAR_ROW are past FAR_Z" % far)
    emit("MOUNT_TOP     EQU %d   ; first line of the mountain strip"
         % S.mountains_top())
    emit("PANO_Y0       EQU %d   ; first line of the panorama (a character row)"
         % S.pano_y0())
    emit("PANO_WORDS    EQU %d   ; panorama width in CRTC words (4 pixels)"
         % S.PANO_WORDS)
    emit("ROAD_AREA_Y   EQU %d   ; first line of the road part's memory"
         % S.ROAD_AREA_Y)
    emit("LAST_Y        EQU %d   ; the road's last line, from ROAD_AREA_Y"
         % (G.ROAD_END - 1 - S.ROAD_AREA_Y))
    emit("")
    emit("BORDER_HW     EQU #%02X" % (0x40 + G.FIRMWARE[G.BORDER_FW][0]))
    emit(";; the border where the ruptures show it: above the sky, below the")
    emit(";; mountains")
    emit("BORDER_TOP_HW EQU #%02X" % (0x40 + G.pen_hw(S.BORDER_TOP)))
    emit("BORDER_LOW_HW EQU #%02X" % (0x40 + G.pen_hw(S.BORDER_LOW)))
    emit("SOLID_GROUND  EQU #%02X" % G.m0_solid(G.GROUND_PEN))
    return lines


def consts_data():
    return [";; Generated by tools/mkgfx.py - do not edit.", "",
            ";; palette: Gate Array colour bytes (#40 + hardware colour), pens 0..15",
            "palette_hw",
            "    defb " + ",".join("#%02X" % (0x40 + G.pen_hw(i)) for i in range(16))]


def gfx():
    lines = [";; Generated by tools/mkgfx.py - do not edit.",
             ";; Everything here is drawn on the HUD's own background pen, so",
             ";; it is copied to the screen, never masked.", ""]
    emit = lines.append

    # big glyphs: 4 bytes x 18 lines
    names = [str(d) for d in range(10)] + ["N"]
    emit(";; big glyphs, 4 bytes x 18 lines, each line twice: 9 lines kept;")
    emit(";; 0-9 then N (gear neutral)")
    emit("BIG_W EQU 4")
    emit("BIG_H EQU 18")
    emit("big_glyphs")
    for n in names:
        emit("; " + n)
        rows = encode_rows(S.big_glyph(n))
        assert all(rows[i] == rows[i + 1] for i in range(0, len(rows), 2))
        defb_rows(emit, rows[::2])
    emit("")

    emit(";; small glyphs, 3 bytes x 8 lines: the digits 0-9, then the space")
    emit(";; and the letters of the messages (scene.py MSG_GLYPHS)")
    emit("SMALL_W EQU 3")
    emit("SMALL_H EQU 8")
    emit("small_digits")
    for ch in S.MSG_GLYPHS:
        emit("; %s" % ch)
        defb_rows(emit, encode_rows(S.small_glyph(ch)))
    emit("")

    # the messages: MSG_W glyph numbers each, centred
    emit(";; the HUD's messages (scene.py MESSAGES), MSG_W glyphs each")
    emit("MSG_W EQU %d" % S.MSG_W)
    emit("MSG_X EQU %d" % (S.MSG_X // 2))
    emit("MSG_Y EQU %d" % S.HUD["message"][1])
    emit("MSG_SPACE EQU %d" % S.MSG_GLYPHS.index(" "))
    for n, m in enumerate(S.MESSAGES[:S.MSG_FORK]):
        name = "MSG_" + (m.replace(" ", "_").strip("!_0123456789") if m else "NONE")
        if n == S.MSG_ENTRY:
            name = "MSG_ENTRY"
        emit("%-17s EQU %d" % (name, n))
    emit("MSG_FORK          EQU %d   ; + a stage's level: its fork's" % S.MSG_FORK)
    stage = S.MESSAGES.index("STAGE 1")
    emit("MSG_STAGE_N       EQU %d   ; (msg_texts) STAGE's digit, the game's"
         % (S.MSG_W * stage + S.msg_cells(stage).index(1)))
    # the best time's: its place, a cell, the minute, ', the seconds, ", the
    # hundredths (race.asm: entry_text)
    cells = S.msg_cells(S.MSG_ENTRY)
    at = cells.index(1)
    assert [S.MSG_GLYPHS[g] for g in cells[at:at + 9]] == list("1 0'00\"00")
    emit("MSG_ENTRY_AT      EQU %d   ; (msg_texts) a best time's place, then"
         % (S.MSG_W * S.MSG_ENTRY + at))
    emit("                          ; a cell on its m'ss\"cc")
    emit("msg_texts")
    for n in range(len(S.MESSAGES)):
        emit("    defb " + ",".join(str(v) for v in S.msg_cells(n)) + "   ; " + S.MESSAGES[n])
    emit("")

    # labels: width in bytes, 8 lines (the HUD's words: labels(), as masks)
    emit(";; labels: defb width in bytes, then 8 lines of bytes")
    labels = [("lbl_apos", "'", S.VALUE_PEN), ("lbl_quote", '"', S.VALUE_PEN)]
    widths = {}
    for name, text, pen in labels:
        rows = pad_even(S.small_text(text, pen))
        enc = encode_rows(rows)
        widths[name] = len(enc[0])
        emit("%s" % name)
        emit("    defb %d" % len(enc[0]))
        defb_rows(emit, enc)
    emit("")

    # HUD positions, in bytes and lines
    H = S.HUD
    sp = S.small_text("SPEED")
    speed_x = (G.SCR_W - len(sp[0])) // 2 // 2 * 2
    pos = dict(
        TIME_LBL=H["time_label"], TIME_VAL=H["time_value"],
        SPEED_LBL=(speed_x, H["speed_label"][1]), SPEED_GAUGE=H["speed_gauge"],
        GEAR=H["gear"], TOTAL_LBL=H["total_label"], TOTAL_VAL=H["total_value"],
        CP_LBL=H["cp_label"], CP_GAUGE=H["cp_gauge"])
    emit(";; HUD layout: x in bytes, y in lines")
    for k, (x, y) in pos.items():
        assert x % 2 == 0, k
        emit("%s_X EQU %d" % (k, x // 2))
        emit("%s_Y EQU %d" % (k, y))
    emit("GAUGE_SEGS EQU %d" % S.GAUGE_SEGS)
    emit("GAUGE_H    EQU %d" % S.GAUGE_H)
    # total time m'ss"cc: digit x offsets (bytes) and separator positions
    emit(";; total time m'ss\"cc: byte offsets of the six digits and two marks")
    xs = []
    marks = []
    x = 0
    for ch in "0'00\"00":
        if ch.isdigit():
            xs.append(x // 2)
            x += 6
        else:
            marks.append(x // 2)
            x += 4 if ch == "'" else 6
    emit("total_digit_x")
    emit("    defb " + ",".join(str(v) for v in xs))
    emit("TOTAL_APOS_X  EQU %d" % marks[0])
    emit("TOTAL_QUOTE_X EQU %d" % marks[1])
    emit("")

    # gauges: per segment the pair of bytes (3 lit pixels + 1 background)
    emit(";; gauge segments: two bytes per segment, by segment index")
    for name, rev in (("cp_seg", False), ("speed_seg", True)):
        emit(name)
        for s in range(S.GAUGE_SEGS):
            zone = s * 4 // S.GAUGE_SEGS
            pen = S.GAUGE_ZONES[3 - zone] if rev else S.GAUGE_ZONES[zone]
            emit("    defb #%02X,#%02X" % (G.m0_byte(pen, pen),
                                         G.m0_byte(pen, S.HUD_BG)))
    emit("SEG_OFF0 EQU #%02X" % G.m0_byte(G.PEN["BLACK"], G.PEN["BLACK"]))
    emit("SEG_OFF1 EQU #%02X" % G.m0_byte(G.PEN["BLACK"], S.HUD_BG))
    emit("")

    # sky: per line from SKY_Y to the panorama, a 2-byte repeating pattern
    top = S.mountains_top()
    emit(";; sky lines %d..%d: the two bytes that repeat across each line" %
         (G.SKY_Y, S.pano_y0() - 1))
    emit("sky_pairs")
    for y in range(G.SKY_Y, S.pano_y0()):
        p = [S.sky_pen(x, y) for x in range(4)]
        emit("    defb #%02X,#%02X" % (G.m0_byte(p[0], p[1]), G.m0_byte(p[2], p[3])))
    emit("")

    # The track (tools/course.py): segment lists the game works out a few
    # entries ahead of the camera (course_fill).
    import course as T
    def seg_list(name, comment, segs, end):
        emit(";; " + comment)
        emit(name)
        for i in range(0, len(segs), 8):
            emit("    defb " + ",".join("%d,%d" % (n, v) for n, v in segs[i:i + 8]))
        emit("    defb 0,%d" % end)
    emit(";; the track: segments (n, v) - n entries of straight road (v = 0), a")
    emit(";; curve to level v (|v| <= CURVE_K) or a hill of v (|v| >= 16); then")
    emit(";; 0,0: round again, 0,1: straight on for good, or 0,2: a stage's end,")
    emit(";; the next as the fork goes (tools/course.py)")
    seg_list("course_demo", "the demo's loop", T.DEMO, 0)
    for i, st in enumerate(T.STAGES):
        seg_list("course_st%d" % i, "stage %d, %s" % (i, st["name"]), st["segs"], 2)
    seg_list("course_finish", "past the last checkpoint", T.FINISH, 1)
    emit("course_hold EQU course_finish+%d   ; (straight on: its end)" % (2 * len(T.FINISH)))
    emit(";; the props along each (src/props.asm): per prop the depth from the last")
    emit(";; (the first: from the course's start) in 16 units, then its kind |")
    emit(";; lateral class << 4 | #80 on the left; at the end the depth to the")
    emit(";; course's end and #FF (round again), or 0,#FE (tools/course.py prop_list)")
    for name, lst in ([("props_demo", T.prop_list(T.demo_props(), len(T.entries(T.DEMO)) * T.ENTRY))]
                      + [("props_st%d" % i, T.prop_list(T.stage_props(i)))
                         for i in range(len(T.STAGES))]):
        emit(name)
        for i in range(0, len(lst), 16):
            emit("    defb " + ",".join("#%02X" % v for v in lst[i:i + 16]))
    assert lst[-2:] == [0, 0xFE]
    emit("props_none EQU $-2   ; (none: the last list's end)")
    emit(";; per stage: its segments and its props (stage_fork)")
    emit("stage_lists")
    for i in range(len(T.STAGES)):
        emit("    defw course_st%d,props_st%d" % (i, i))
    for level in range(T.LEVELS - 1):
        assert [T.next_stage(level, side) for side in (0, 1)] == [2 * level + 1, 2 * level + 2]
    emit("STAGES    EQU %d   ; a race's (its levels: 2 l + 1 + side follows level l's)"
         % T.LEVELS)
    emit("STAGE_LEN EQU %d   ; depth units a stage" % (T.STAGE_LEN * T.ENTRY))
    emit("FORK_Z    EQU %d   ; ... from its end on, its fork's message" % (T.FORK_AHEAD * T.ENTRY))
    emit("HILL_RAMP EQU %d" % T.HILL_RAMP)
    emit(";; a quarter of a sine, 0..255")
    emit("sine_q")
    for i in range(0, len(T.SINE_Q), 16):
        emit("    defb " + ",".join(str(v) for v in T.SINE_Q[i:i + 16]))
    emit(";; the pens a stage colours (#FF: no more), and each stage's colours")
    emit(";; for them: %s" % ", ".join(T.STAGE_PENS))
    emit("stage_pen_ids")
    emit("    defb " + ",".join(str(G.PEN[p]) for p in T.STAGE_PENS) + ",#FF")
    emit("STAGE_GROUND EQU %d   ; (the ground's: the border below the mountains)"
         % T.STAGE_PENS.index(G.PENS[G.GROUND_PEN][0]))
    emit("stage_hw")
    for i, st in enumerate(T.STAGES):
        emit("    defb " + ",".join("#%02X" % (0x40 + G.FIRMWARE[c][0]) for c in T.stage_fw(i))
             + "   ; " + st["name"])
    emit("")

    lines += horizon(top)
    return lines


def horizon(top):
    """The mountains: the whole panorama, from the character row they start
    in, over the sky - a column (a word wide) at a time, as ring_col writes
    them."""
    lines = []
    emit = lines.append
    t, rows = S.horizon_panorama()
    assert t == top
    y0 = S.pano_y0()
    full = [[S.sky_pen(x, y) for x in range(S.PANORAMA_W)] for y in range(y0, top)]
    full += rows
    enc = encode_rows(full)
    assert len(enc) % 8 == 0
    nrows = len(enc) // 8
    cols = [[b for row in enc for b in row[2 * c:2 * c + 2]] for c in range(S.PANO_WORDS)]
    # a column's character rows - its two bytes on each of 8 lines, top to
    # bottom: 16 bytes - are many columns' (the sky, the mountains' bodies):
    # each different one is kept once
    rows, ptrs = {}, []
    for col in cols:
        ptrs.append([rows.setdefault(tuple(col[16 * r:16 * r + 16]), len(rows))
                     for r in range(nrows)])
    emit(";; the panorama, lines %d..%d: for each of the %d words across, its"
         % (y0, G.BLOCK_BOTTOM - 1, S.PANO_WORDS))
    emit(";; %d character rows' addresses in pano_rows - each row its two bytes on"
         % nrows)
    emit(";; each of its 8 lines, top to bottom, %d different ones of %d"
         % (len(rows), nrows * S.PANO_WORDS))
    emit("PANO_COL_ROWS EQU %d" % nrows)
    emit("pano_cols")
    for p in ptrs:
        emit("    defw " + ",".join("pano_rows+%d" % (16 * i) for i in p))
    emit("pano_rows")
    defb_rows(emit, sorted(rows, key=rows.get))
    emit("")
    return lines


LABELS = [("TIME", "TIME_LBL"), ("SPEED", "SPEED_LBL"), ("TOTAL TIME", "TOTAL_LBL"),
          ("CHECKPOINT", "CP_LBL")]


def label_mask(text):
    """A label's mask, as scene.small_text lays its letters out before the
    shadow: rows of '#' and '.'."""
    rows = [""] * 7
    for ch in text:
        g = S.SMALL[S.SMALL_NAMES.get(ch, ch)]
        for j in range(7):
            rows[j] += g[j] + "."
    return [r[:-1] for r in rows]


def labels():
    """src/gen/labels.asm: the HUD's words as masks, for src/labels.asm."""
    lines = [";; Generated by tools/mkgfx.py - do not edit.", ""]
    emit = lines.append
    vals = dict(GROUND=S.HUD_BG, SHADOW=S.SHADOW, PEN=S.LABEL_PEN)
    for a in vals.values():             # (a right pixel's bits: a left one's
        assert G.m0_byte(0, a) == G.m0_byte(a, 0) >> 1     # a bit on)
        for b in vals.values():
            assert G.m0_byte(a, b) == G.m0_byte(a, 0) | G.m0_byte(b, 0) >> 1
    emit(";; a left pixel's bits: the ground, the shadow, the pen")
    for k, p in vals.items():
        emit("LBL_%-7s EQU #%02X" % (k, G.m0_byte(p, 0)))
    widths = []
    emit(";; per label: x (bytes), y, its mask's width (pixels), bytes a row,")
    emit(";; then its rows, first pixel in bit 7; #FF at the end")
    emit("lbl_masks")
    for text, pos in LABELS:
        mask = label_mask(text)
        w = len(mask[0])
        nb = (w + 7) // 8
        widths.append(w)
        # (as gfx() had them: scene.small_text, padded to even)
        want = encode_rows(pad_even(S.small_text(text)))
        assert len(want) == 8 and len(want[0]) == (w + 2) // 2
        emit("; " + text)
        emit("    defb %s_X,%s_Y,%d,%d" % (pos, pos, w, nb))
        flat = []
        for r in mask:
            bits = r.ljust(nb * 8, ".")
            flat += [int(bits[i:i + 8].replace("#", "1").replace(".", "0"), 2)
                     for i in range(0, nb * 8, 8)]
        emit("    defb " + ",".join("#%02X" % b for b in flat))
    emit("    defb #FF")
    emit("LBL_PIXELS  EQU %d   ; (the widest mask's pixels, its shadow's, padded)"
         % (max(widths) + 2))
    emit("LBL_OUT_W   EQU %d   ; (its bytes)" % ((max(widths) + 2) // 2))
    return lines


def main():
    gen = os.path.join(ROOT, "src", "gen")
    os.makedirs(gen, exist_ok=True)
    open(os.path.join(gen, "consts.asm"), "w").write("\n".join(consts()) + "\n")
    open(os.path.join(gen, "consts_data.asm"), "w").write("\n".join(consts_data()) + "\n")
    open(os.path.join(gen, "gfx.asm"), "w").write("\n".join(gfx()) + "\n")
    open(os.path.join(gen, "labels.asm"), "w").write("\n".join(labels()) + "\n")
    print("src/gen/consts.asm, src/gen/gfx.asm, src/gen/labels.asm written")


if __name__ == "__main__":
    main()
